using System.Numerics;
using Biz.Bizadm.S2Protocol.NET.Generator.Layout;

namespace Biz.Bizadm.S2Protocol.NET.Generator.Emit;

// 한 버전의 타입(struct → sealed class, choice → 추상 클래스 + 경우 클래스, enum)과 코덱 메서드를 출력한다.
// 메서드는 타입이 도달하는 코덱(bitpacked/versioned)만 만든다.
internal sealed class VersionEmitter
{
    private const string Lib = "global::Biz.Bizadm.S2Protocol.NET";

    private readonly ProtocolModel _model;
    private readonly TypeCatalog _catalog;

    public VersionEmitter(ProtocolModel model)
    {
        _model = model;
        RootNamespace = $"Biz.Bizadm.S2Protocol.NET.Versions.Protocol{model.Build:D5}";
        _catalog = new TypeCatalog(RootNamespace);

        var roots = model.Roots.Roots;
        void Mark(string pyName, Codecs codec)
        {
            if (roots.TryGetValue(pyName, out var fullName))
                _catalog.Mark(model.Layout.ForDecl(fullName), codec);
        }
        void MarkTable(string stream, Codecs codec)
        {
            if (model.Roots.EventTables.TryGetValue(stream, out var table))
                foreach (var (_, name) in table.Values)
                    _catalog.Mark(model.Layout.ForDecl(name), codec);
        }

        Mark("replay_header_typeid", Codecs.Versioned);
        Mark("game_details_typeid", Codecs.Versioned);
        Mark("tracker_eventid_typeid", Codecs.Versioned);
        MarkTable("tracker", Codecs.Versioned);
        Mark("replay_initdata_typeid", Codecs.BitPacked);
        Mark("svaruint32_typeid", Codecs.BitPacked);
        Mark("replay_userid_typeid", Codecs.BitPacked);
        Mark("game_eventid_typeid", Codecs.BitPacked);
        Mark("message_eventid_typeid", Codecs.BitPacked);
        MarkTable("game", Codecs.BitPacked);
        MarkTable("message", Codecs.BitPacked);
    }

    public string RootNamespace { get; }

    public int TypeCount { get; private set; }

    public string Emit()
    {
        var w = new CodeWriter();
        w.Line("// <auto-generated/>");
        w.Line($"// s2protocol protocol{_model.Build:D5} — Biz.Bizadm.S2Protocol.NET.Generator emit");
        w.Line("#nullable enable");
        w.Line("using Biz.Bizadm.S2Protocol.NET.Decoding;");
        w.Line("using Biz.Bizadm.S2Protocol.NET.Encoding;");
        foreach (var group in _catalog.TopLevel.GroupBy(t => t.Namespace!).OrderBy(g => g.Key, StringComparer.Ordinal))
        {
            w.Line();
            w.Open($"namespace {group.Key}");
            bool first = true;
            foreach (var type in group.OrderBy(t => t.Name, StringComparer.Ordinal))
            {
                if (!first) w.Line();
                first = false;
                EmitType(w, type);
            }
            w.Close();
        }
        return w.ToString();
    }

    private void EmitType(CodeWriter w, EmittedType type)
    {
        TypeCount++;
        switch (type.Type)
        {
            case WInt enumType:
                EmitEnum(w, type, enumType);
                break;
            case WStruct structType:
                EmitStruct(w, type, structType);
                break;
            case WChoice choice:
                EmitChoice(w, type, choice);
                break;
        }
    }

    private static void EmitEnum(CodeWriter w, EmittedType type, WInt enumType)
    {
        var names = new HashSet<string>();
        w.Open($"public enum {type.Name} : {IntClr(enumType)}");
        foreach (var member in enumType.Members!)
        {
            string name = ClrNames.Member(member.Name);
            if (!names.Add(name))
                throw new InvalidOperationException($"{type.FullName}: duplicate enum member '{name}'.");
            w.Line($"{name} = {member.Value},");
        }
        w.Close();
    }

    private void EmitStruct(CodeWriter w, EmittedType type, WStruct structType)
    {
        var members = new HashSet<string> { type.Name };
        foreach (var nested in type.Nested)
            Claim(members, nested.Name, type);

        w.Open($"public sealed partial class {type.Name}");
        foreach (var field in structType.Fields)
        {
            string name = ClrNames.Member(field.Name);
            Claim(members, name, type);
            w.Line($"[{Lib}.S2Field(\"{field.Name}\")]");
            w.Line($"public {TypeName(field.Type)} {name} {{ get; set; }}{Initializer(field.Type)}");
            w.Line();
        }
        foreach (var nested in type.Nested)
        {
            EmitType(w, nested);
            w.Line();
        }

        if (type.Codecs.HasFlag(Codecs.BitPacked))
        {
            w.Open($"internal static {type.Name} ReadBitPacked(BitPackedDecoder d)");
            w.Line($"var r = new {type.Name}();");
            foreach (var field in structType.Fields)
                w.Line($"r.{ClrNames.Member(field.Name)} = {ReadBitPacked(field.Type)};");
            w.Line("return r;");
            w.Close();
            w.Line();
            w.Open($"internal static void WriteBitPacked(BitPackedEncoder e, {type.Name} v)");
            foreach (var field in structType.Fields)
                w.Line(WriteBitPacked(field.Type, $"v.{ClrNames.Member(field.Name)}", 0) + ";");
            w.Close();
            w.Line();
        }
        if (type.Codecs.HasFlag(Codecs.Versioned))
        {
            w.Open($"internal static {type.Name} ReadVersioned(VersionedDecoder d)");
            w.Line($"var r = new {type.Name}();");
            w.Open("for (long n = d.ReadStructFieldCount(); n > 0; n--)");
            w.Open("switch (d.ReadVInt())");
            foreach (var field in structType.Fields)
                w.Line($"case {field.Tag}: r.{ClrNames.Member(field.Name)} = {ReadVersioned(field.Type)}; break;");
            w.Line("default: d.SkipInstance(); break;");
            w.Close();
            w.Close();
            w.Line("return r;");
            w.Close();
            w.Line();
            w.Open($"internal static void WriteVersioned(VersionedEncoder e, {type.Name} v)");
            w.Line($"e.WriteStructFieldCount({structType.Fields.Count});");
            foreach (var field in structType.Fields)
            {
                w.Line($"e.WriteVInt({field.Tag});");
                w.Line(WriteVersioned(field.Type, $"v.{ClrNames.Member(field.Name)}", 0) + ";");
            }
            w.Close();
            w.Line();
        }
        w.Close();
    }

    private void EmitChoice(CodeWriter w, EmittedType type, WChoice choice)
    {
        var members = new HashSet<string> { type.Name, "UnknownCase" };
        foreach (var nested in type.Nested)
            Claim(members, nested.Name, type);

        w.Open($"public abstract partial class {type.Name}");
        foreach (var @case in choice.Cases)
        {
            string name = ClrNames.Member(@case.Name);
            Claim(members, name, type);
            w.Line($"[{Lib}.S2Field(\"{@case.Name}\")]");
            if (@case.Type is WNull)
            {
                w.Line($"public sealed partial class {name} : {type.Name} {{ }}");
            }
            else
            {
                if (name == "Value")
                    throw new InvalidOperationException($"{type.FullName}: case '{name}' collides with its Value property.");
                w.Open($"public sealed partial class {name} : {type.Name}");
                w.Line($"public {TypeName(@case.Type)} Value {{ get; set; }}{Initializer(@case.Type)}");
                w.Close();
            }
            w.Line();
        }
        w.Line("// versioned에서 모르는 태그: Python처럼 값을 건너뛴다. 인코딩할 수 없다.");
        w.Open($"public sealed partial class UnknownCase : {type.Name}");
        w.Line("public long Tag { get; init; }");
        w.Close();
        w.Line();
        foreach (var nested in type.Nested)
        {
            EmitType(w, nested);
            w.Line();
        }

        if (type.Codecs.HasFlag(Codecs.BitPacked))
        {
            w.Open($"internal static {type.Name} ReadBitPacked(BitPackedDecoder d)");
            w.Line($"long tag = d.ReadInt({Long(choice.Offset)}, {choice.Bits});");
            w.Open("return tag switch");
            foreach (var @case in choice.Cases)
                w.Line($"{@case.Tag} => {NewCase(@case, ReadBitPacked)},");
            w.Line($"_ => throw new CorruptedReplayException($\"Unknown choice tag {{tag}} for {type.Name}.\"),");
            w.Close(";");
            w.Close();
            w.Line();
            w.Open($"internal static void WriteBitPacked(BitPackedEncoder e, {type.Name} v)");
            w.Open("switch (v)");
            foreach (var @case in choice.Cases)
            {
                string name = ClrNames.Member(@case.Name);
                string tag = $"e.WriteInt({@case.Tag}, {Long(choice.Offset)}, {choice.Bits});";
                w.Line(@case.Type is WNull
                    ? $"case {name}: {tag} break;"
                    : $"case {name} c: {tag} {WriteBitPacked(@case.Type, "c.Value", 0)}; break;");
            }
            w.Line($"default: throw new global::System.InvalidOperationException($\"Cannot encode {{v?.GetType().Name ?? \"null\"}} as {type.Name}.\");");
            w.Close();
            w.Close();
            w.Line();
        }
        if (type.Codecs.HasFlag(Codecs.Versioned))
        {
            w.Open($"internal static {type.Name} ReadVersioned(VersionedDecoder d)");
            w.Line("long tag = d.ReadChoiceTag();");
            w.Open("switch (tag)");
            foreach (var @case in choice.Cases)
                w.Line($"case {@case.Tag}: return {NewCase(@case, ReadVersioned)};");
            w.Line("default: d.SkipInstance(); return new UnknownCase { Tag = tag };");
            w.Close();
            w.Close();
            w.Line();
            w.Open($"internal static void WriteVersioned(VersionedEncoder e, {type.Name} v)");
            w.Open("switch (v)");
            foreach (var @case in choice.Cases)
            {
                string name = ClrNames.Member(@case.Name);
                string tag = $"e.WriteChoiceTag({@case.Tag});";
                w.Line(@case.Type is WNull
                    ? $"case {name}: {tag} break;"
                    : $"case {name} c: {tag} {WriteVersioned(@case.Type, "c.Value", 0)}; break;");
            }
            w.Line($"default: throw new global::System.InvalidOperationException($\"Cannot encode {{v?.GetType().Name ?? \"null\"}} as {type.Name}.\");");
            w.Close();
            w.Close();
            w.Line();
        }
        w.Close();
    }

    private static string NewCase(WCase @case, Func<WireType, string> read)
    {
        string name = ClrNames.Member(@case.Name);
        return @case.Type is WNull ? $"new {name}()" : $"new {name} {{ Value = {read(@case.Type)} }}";
    }

    private static void Claim(HashSet<string> members, string name, EmittedType owner)
    {
        if (!members.Add(name))
            throw new InvalidOperationException($"{owner.FullName}: member name '{name}' collides.");
    }

    // ---- C# 타입 ----

    private string TypeName(WireType type) => type switch
    {
        WInt { Members: not null, DeclName: not null } => _catalog.Get(type).FullName,
        WInt i => IntClr(i),
        WBool => "bool",
        WFourCC => $"{Lib}.FourCC",
        WBlob => "byte[]",
        WBitArray => $"{Lib}.S2BitArray",
        WArray a => TypeName(a.Element) + "[]",
        WOptional o => TypeName(o.Element) + "?",
        WStruct or WChoice => _catalog.Get(type).FullName,
        _ => throw new NotSupportedException($"No C# type for {type.GetType().Name}."),
    };

    private static bool IsValueType(WireType type) => type is WInt or WBool or WFourCC;

    private static string Initializer(WireType type) => type switch
    {
        WBlob or WArray => " = [];",
        WBitArray => " = new(0, []);",
        WStruct => " = new();",
        WChoice => " = null!;",
        _ => "",
    };

    // 와이어로 표현 가능한 범위(offset ~ offset + 2^bits - 1)로 정한다.
    private static string IntClr(WInt type)
    {
        BigInteger min = type.Offset, max = type.Offset + (BigInteger.One << type.Bits) - 1;
        if (min >= int.MinValue && max <= int.MaxValue) return "int";
        if (min >= long.MinValue && max <= long.MaxValue) return "long";
        // ulong 코덱(ReadUInt64/WriteUInt64)은 offset을 더하지 않으므로 offset 0만 허용한다.
        if (min == 0 && max <= ulong.MaxValue) return "ulong";
        throw new NotSupportedException($"Integer range ({min}, {max}) does not fit a CLR type.");
    }

    private static string Long(BigInteger value) => value == long.MinValue ? "long.MinValue" : $"{value}L";

    // ---- bitpacked ----

    private string ReadBitPacked(WireType type) => type switch
    {
        WInt i => IntClr(i) == "ulong"
            ? Cast(i, $"d.ReadUInt64({i.Bits})")
            : Cast(i, $"d.ReadInt({Long(i.Offset)}, {i.Bits})"),
        WBool => "d.ReadBool()",
        WFourCC => "d.ReadFourCC()",
        WBlob b => $"d.ReadBlob({Long(b.Offset)}, {b.Bits})",
        WBitArray b => $"d.ReadBitArray({Long(b.Offset)}, {b.Bits})",
        WArray a => $"d.ReadArray({Long(a.Offset)}, {a.Bits}, () => {ReadBitPacked(a.Element)})",
        WOptional o => $"d.{(IsValueType(o.Element) ? "ReadOptionalValue" : "ReadOptional")}(() => {ReadBitPacked(o.Element)})",
        WStruct or WChoice => $"{_catalog.Get(type).FullName}.ReadBitPacked(d)",
        _ => throw new NotSupportedException($"Cannot read {type.GetType().Name}."),
    };

    private string WriteBitPacked(WireType type, string value, int depth) => type switch
    {
        WInt i => IntClr(i) == "ulong"
            ? $"e.WriteUInt64((ulong){value}, {i.Bits})"
            : $"e.WriteInt((long){value}, {Long(i.Offset)}, {i.Bits})",
        WBool => $"e.WriteBool({value})",
        WFourCC => $"e.WriteFourCC({value})",
        WBlob b => $"e.WriteBlob({value}, {Long(b.Offset)}, {b.Bits})",
        WBitArray b => $"e.WriteBitArray({value}, {Long(b.Offset)}, {b.Bits})",
        WArray a => $"e.WriteArray({value}, {Long(a.Offset)}, {a.Bits}, x{depth} => {WriteBitPacked(a.Element, $"x{depth}", depth + 1)})",
        WOptional o => $"e.{(IsValueType(o.Element) ? "WriteOptionalValue" : "WriteOptional")}({value}, x{depth} => {WriteBitPacked(o.Element, $"x{depth}", depth + 1)})",
        WStruct or WChoice => $"{_catalog.Get(type).FullName}.WriteBitPacked(e, {value})",
        _ => throw new NotSupportedException($"Cannot write {type.GetType().Name}."),
    };

    // ---- versioned ----

    private string ReadVersioned(WireType type) => type switch
    {
        // versioned vint는 bounds를 강제하지 않으므로 좁히는 변환을 checked로 해 잘림 대신 예외를 낸다.
        WInt i => IntClr(i) == "ulong" ? Cast(i, "d.ReadUInt64()") : CheckedCast(i, "d.ReadInt()"),
        WBool => "d.ReadBool()",
        WFourCC => "d.ReadFourCC()",
        WBlob => "d.ReadBlob()",
        WBitArray => "d.ReadBitArray()",
        WArray a => $"d.ReadArray(() => {ReadVersioned(a.Element)})",
        WOptional o => $"d.{(IsValueType(o.Element) ? "ReadOptionalValue" : "ReadOptional")}(() => {ReadVersioned(o.Element)})",
        WStruct or WChoice => $"{_catalog.Get(type).FullName}.ReadVersioned(d)",
        _ => throw new NotSupportedException($"Cannot read {type.GetType().Name}."),
    };

    private string WriteVersioned(WireType type, string value, int depth) => type switch
    {
        WInt i => IntClr(i) == "ulong" ? $"e.WriteUInt64((ulong){value})" : $"e.WriteInt((long){value})",
        WBool => $"e.WriteBool({value})",
        WFourCC => $"e.WriteFourCC({value})",
        WBlob => $"e.WriteBlob({value})",
        WBitArray => $"e.WriteBitArray({value})",
        WArray a => $"e.WriteArray({value}, x{depth} => {WriteVersioned(a.Element, $"x{depth}", depth + 1)})",
        WOptional o => $"e.{(IsValueType(o.Element) ? "WriteOptionalValue" : "WriteOptional")}({value}, x{depth} => {WriteVersioned(o.Element, $"x{depth}", depth + 1)})",
        WStruct or WChoice => $"{_catalog.Get(type).FullName}.WriteVersioned(e, {value})",
        _ => throw new NotSupportedException($"Cannot write {type.GetType().Name}."),
    };

    // 정수 읽기 결과(long/ulong)를 필드 타입(int, enum)으로 바꾼다.
    private string Cast(WInt type, string read)
    {
        string clr = TypeName(type);
        return clr is "long" or "ulong" ? read : $"({clr}){read}";
    }

    private string CheckedCast(WInt type, string read)
    {
        string clr = TypeName(type);
        return clr is "long" or "ulong" ? read : $"checked(({clr}){read})";
    }
}
