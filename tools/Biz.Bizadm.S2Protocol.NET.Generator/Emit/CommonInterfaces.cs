using Biz.Bizadm.S2Protocol.NET.Generator.Layout;

namespace Biz.Bizadm.S2Protocol.NET.Generator.Emit;

// 버전 공통 인터페이스(설계 D3). 같은 fullname의 struct가 정의된 모든 버전에서 (원본 이름, 키)가 같은 필드의 교집합.
// 키: 정수는 CLR 타입, enum은 E:기반형, struct는 I:fullname, 배열 L(k), optional O(k), blob byte[], bitarray, fourcc, bool.
// choice·익명 struct는 키가 없어 빠진다. enum이 들어간 배열은 C# 변환이 없어 뺀다.
internal sealed class CommonInterfaces
{
    public const string RootNamespace = "Biz.Bizadm.S2Protocol.NET.Common";
    private const string Lib = "global::Biz.Bizadm.S2Protocol.NET";

    public sealed record Field(string WireName, string Key);

    public sealed record Interface(string DeclName, string Name, string Namespace, IReadOnlyList<Field> Fields)
    {
        public string FullName => $"global::{Namespace}.{Name}";
    }

    // 한 버전의 최상위 타입 종류와 struct 필드 키.
    public sealed record VersionSummary(int Build, Dictionary<string, string> Kinds, Dictionary<string, List<Field>> Structs);

    public Dictionary<string, Interface> ByDecl { get; } = [];

    public List<string> Warnings { get; } = [];

    public static VersionSummary Summarize(int build, TypeCatalog catalog)
    {
        var kinds = new Dictionary<string, string>();
        var structs = new Dictionary<string, List<Field>>();
        foreach (var type in catalog.TopLevel)
        {
            string declName = type.Type.DeclName!;
            kinds[declName] = type.Type switch { WStruct => "struct", WChoice => "choice", _ => "enum" };
            if (type.Type is WStruct structType)
                structs[declName] = structType.Fields
                    .Select(f => (f.Name, Key: KeyOf(f.Type)))
                    .Where(f => f.Key is not null)
                    .Select(f => new Field(f.Name, f.Key!))
                    .ToList();
        }
        return new VersionSummary(build, kinds, structs);
    }

    public static CommonInterfaces Build(IReadOnlyList<VersionSummary> versions)
    {
        var result = new CommonInterfaces();
        var latestFirst = versions.OrderByDescending(v => v.Build).ToList();

        var candidates = new HashSet<string>();
        foreach (var declName in versions.SelectMany(v => v.Kinds.Keys).Distinct())
        {
            var kinds = versions.Where(v => v.Kinds.ContainsKey(declName)).Select(v => v.Kinds[declName]).Distinct().ToList();
            if (kinds is ["struct"])
                candidates.Add(declName);
            else if (kinds.Contains("struct"))
                result.Warnings.Add($"{declName}: kinds differ across builds ({string.Join(",", kinds)}); no common interface.");
        }

        var names = new HashSet<string>();
        foreach (string declName in candidates.Order(StringComparer.Ordinal))
        {
            var present = latestFirst.Where(v => v.Structs.ContainsKey(declName)).ToList();
            var common = present.Skip(1).Aggregate(
                present[0].Structs[declName].ToHashSet(),
                (set, v) => { set.IntersectWith(v.Structs[declName]); return set; });
            var fields = present[0].Structs[declName]
                .Where(f => common.Contains(f) && References(f.Key).All(candidates.Contains))
                .ToList();

            string typeName = ClrNames.TypeName(declName);
            string name = "I" + (typeName.Length > 1 && typeName[0] == 'S' && char.IsUpper(typeName[1]) ? typeName[1..] : typeName);
            string ns = ClrNames.Namespace(RootNamespace, declName);
            if (!names.Add($"{ns}.{name}"))
                throw new InvalidOperationException($"Common interface name {ns}.{name} collides ({declName}).");
            result.ByDecl[declName] = new Interface(declName, name, ns, fields);
        }
        return result;
    }

    public string Emit()
    {
        var w = new CodeWriter();
        w.Line("// <auto-generated/>");
        w.Line("// s2protocol 버전 공통 인터페이스 — Biz.Bizadm.S2Protocol.NET.Generator emit");
        w.Line("#nullable enable");
        foreach (var group in ByDecl.Values.GroupBy(i => i.Namespace).OrderBy(g => g.Key, StringComparer.Ordinal))
        {
            w.Line();
            w.Open($"namespace {group.Key}");
            bool first = true;
            foreach (var @interface in group.OrderBy(i => i.Name, StringComparer.Ordinal))
            {
                if (!first) w.Line();
                first = false;
                w.Open($"public partial interface {@interface.Name}");
                foreach (var field in @interface.Fields)
                    w.Line($"{ClrType(field.Key)} {ClrNames.Member(field.WireName)} {{ get; }}");
                w.Close();
            }
            w.Close();
        }
        return w.ToString();
    }

    public string ClrType(string key) => key switch
    {
        "bool" or "int" or "long" or "ulong" or "byte[]" => key,
        "fourcc" => $"{Lib}.FourCC",
        "bitarray" => $"{Lib}.S2BitArray",
        _ when key.StartsWith("E:") => key[2..],
        _ when key.StartsWith("I:") => ByDecl[key[2..]].FullName,
        _ when key.StartsWith("L(") => $"global::System.Collections.Generic.IReadOnlyList<{ClrType(key[2..^1])}>",
        _ when key.StartsWith("O(") => ClrType(key[2..^1]) + "?",
        _ => throw new NotSupportedException($"Unknown field key '{key}'."),
    };

    // 클래스 속성 → 인터페이스 속성. enum은 기반형으로 캐스트, 나머지는 암시적 변환(배열 공변성 포함).
    public static string Implementation(string key, string property) => key switch
    {
        _ when key.StartsWith("E:") => $"({key[2..]}){property}",
        _ when key.StartsWith("O(E:") => $"({key[4..^1]}?){property}",
        _ => property,
    };

    private static string? KeyOf(WireType type) => type switch
    {
        WInt { Members: not null, DeclName: not null } i => "E:" + VersionEmitter.IntClr(i),
        WInt i => VersionEmitter.IntClr(i),
        WBool => "bool",
        WFourCC => "fourcc",
        WBlob => "byte[]",
        WBitArray => "bitarray",
        WStruct { DeclName: not null } s => "I:" + s.DeclName,
        WArray a => KeyOf(a.Element) is { } k && !k.Contains("E:") ? $"L({k})" : null,
        WOptional o => KeyOf(o.Element) is { } k ? $"O({k})" : null,
        _ => null,
    };

    private static IEnumerable<string> References(string key)
    {
        int index = 0;
        while ((index = key.IndexOf("I:", index, StringComparison.Ordinal)) >= 0)
        {
            int end = key.IndexOf(')', index);
            yield return end < 0 ? key[(index + 2)..] : key[(index + 2)..end];
            index += 2;
        }
    }
}
